from pathlib import Path
import re, json, hashlib, sys
from collections import Counter
r=Path(sys.argv[1]).resolve()
h=(r/'src/rubik/rubik_transition_tables.h').read_text()
def array(name):
    m=re.search(r"\b"+name+r"\[\d+\]\s*=\s*\{([^}]+)\}",h,re.S)
    assert m, name
    return [int(x) for x in re.findall(r"\d+",m.group(1))]
p=[array('perm_'+f) for f in 'RBD']; o=[array('orient_'+f) for f in 'RBD']
seen={0:(0,15)}; frontier=[0]
for depth in range(1,6):
    nxt=[]
    for key in frontier:
        pp,oo=key>>10,key&1023
        for face in range(3):
            pn,on=pp,oo
            for turn in range(3):
                pn,on=p[face][pn],o[face][on]
                k=(pn<<10)|on
                if k not in seen:
                    seen[k]=(depth,face*3+2-turn)
                    nxt.append(k)
    frontier=nxt
# Verify every stored move goes to a state one step closer to solved.
for key,(depth,move) in seen.items():
    if depth==0: continue
    pp,oo=key>>10,key&1023
    face,turn=divmod(move,3)
    for _ in range(turn+1): pp,oo=p[face][pp],o[face][oo]
    assert seen[(pp<<10)|oo][0]==depth-1
words=[(key<<7)|(seen[key][0]<<4)|seen[key][1] for key in sorted(seen)]
assert all(0<=x<2**32 for x in words)
lines=['# Generated by mytests/build-rubik-near5.py from HW1 transition tables.',
       '# Bits 31:7 = packed state key; 6:4 = distance; 3:0 = next move.',
       '    .section .rodata','    .balign 4',f'    .equ RUBIK_NEAR5_COUNT, {len(words)}','.Lnear5_table:']
for i in range(0,len(words),8): lines.append('    .word '+', '.join(map(str,words[i:i+8])))
lines.append('.Lnear5_end:')
(r/'src/rubik/rubik_distance_up_to_5.inc').write_text('\n'.join(lines)+'\n')
report={'entries':len(words),'bytes':len(words)*4,'depth_counts':dict(sorted(Counter(d for d,m in seen.values()).items())),'all_next_moves_verified':True,'source_sha256':hashlib.sha256(h.encode()).hexdigest()}
(r/'mytests/rubik-near5-generation.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report,indent=2))
